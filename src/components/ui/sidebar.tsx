const SidebarProvider = React.forwardRef<
  HTMLDivElement,
  React.ComponentProps<"div"> & {
    defaultOpen?: boolean
    open?: boolean
    onOpenChange?: (open: boolean) => void
  }
>(({ defaultOpen = true, open: openProp, onOpenChange, className, children, ...props }, ref) => {
  const [open, setOpen] = React.useState(defaultOpen)

  const handleOpenChange = React.useCallback(
    (value: boolean) => {
      setOpen(value)
      onOpenChange?.(value)
    },
    [onOpenChange]
  )

  const value = React.useMemo(
    () => ({
      open: openProp ?? open,
      setOpen: handleOpenChange,
      isMobile: false,
      toggleSidebar: () => handleOpenChange(!(openProp ?? open)),
    }),
    [open, openProp, handleOpenChange]
  )

  return (
    <SidebarContext.Provider value={value}>
      <div
        ref={ref}
        className={cn("group/sidebar-wrapper flex w-full", className)}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
})
SidebarProvider.displayName = "SidebarProvider"

